#!/usr/bin/env python3
"""Regenerate horizontal SVG geometry bounds (requires rsvg-convert and Pillow)."""
import io
import json
import re
import subprocess
from pathlib import Path
from PIL import Image

assets = Path(__file__).resolve().parent
bounds = {}
for path in sorted(assets.glob('*.svg')):
    # A tiny stroke includes open paths; remove its radius from the measured bounds.
    svg = re.sub(r'stroke-width="[^"]*"', 'stroke-width="0.1"', path.read_text())
    svg = svg.replace('currentColor', '#000000')
    png = subprocess.run(['rsvg-convert', '-w', '2400', '-h', '2400'],
                         input=svg.encode(), stdout=subprocess.PIPE, check=True).stdout
    box = Image.open(io.BytesIO(png)).getchannel('A').getbbox()
    if box is None:
        raise ValueError(f'Empty icon: {path}')
    bounds[path.stem] = [round(box[0] / 100 + 0.05, 2),
                         round(box[2] / 100 - 0.05, 2)]
(assets / 'bounds.js').write_text('// Generated by update-bounds.py; horizontal geometry bounds in SVG units.\n'
                                '.pragma library\nvar bounds = ' + json.dumps(bounds, indent=4) + '\n')
print(f'Generated bounds for {len(bounds)} icons.')
